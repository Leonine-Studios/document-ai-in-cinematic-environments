/** Optional columns shown out of the box — none; the user opts in via the "Columns" menu. */
export const DEFAULT_VISIBLE_OPTIONAL_COLUMNS: ReadonlySet<string> = new Set();

/** `shownOptional` holds only the currently-enabled *optional* column keys; non-optional columns are always shown. */
export function isColumnVisible(column: AssetTableColumn, shownOptional: ReadonlySet<string>): boolean {
  return !column.optional || shownOptional.has(column.key);
}

export function visibleColumns(shownOptional: ReadonlySet<string>): AssetTableColumn[] {
  return ASSET_TABLE_COLUMNS.filter((c) => isColumnVisible(c, shownOptional));
}

/** Builds the `grid-template-columns` value for exactly the currently-visible columns. */
export function buildGridTemplate(shownOptional: ReadonlySet<string>): string {
  return visibleColumns(shownOptional)
    .map((c) => c.width)
    .join(" ");
}

