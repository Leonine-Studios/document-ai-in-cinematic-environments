import type { ComfyGraph, ComfyMetadata } from "./types";
import { extractFromPngChunks, isPng } from "./pngChunks";
import { extractJsonValueForKey } from "./jsonScan";

/** A ComfyUI API-format graph is a dict of node id -> `{ class_type, inputs }`; this is enough of a shape check to reject unrelated JSON that happens to have a "prompt" key. */
function looksLikeComfyGraph(value: unknown): value is ComfyGraph {
  if (!value || typeof value !== "object") return false;
  const nodes = Object.values(value as Record<string, unknown>);
  if (nodes.length === 0) return false;
  return nodes.every((node) => Boolean(node) && typeof node === "object" && typeof (node as { class_type?: unknown }).class_type === "string");
}

/** ComfyUI's UI-format workflow JSON always has a top-level `nodes` array. */
function looksLikeComfyWorkflow(value: unknown): boolean {
  return Boolean(value) && typeof value === "object" && Array.isArray((value as { nodes?: unknown }).nodes);
}

function sanitize(raw: ComfyMetadata): ComfyMetadata | null {
  const prompt = looksLikeComfyGraph(raw.prompt) ? raw.prompt : undefined;
  const workflow = looksLikeComfyWorkflow(raw.workflow) ? raw.workflow : undefined;
  if (!prompt && !workflow) return null;
  return { prompt, workflow };
}

/**
 * Best-effort fallback for containers without a clean chunk/tag API in the
 * browser — WebP (EXIF text fields) and MP4/WebM (the "comment" metadata
 * atom the Video Helper Suite's "Video Combine" node writes, and the
 * equivalent on ComfyUI's core `SaveWEBM`/`SaveVideo` nodes). Scans the raw
 * bytes as text for the `"prompt"`/`"workflow"` JSON ComfyUI embeds. Only
 * finds it when it was stored as raw, uncompressed text — a re-encoded or
 * metadata-stripped file yields nothing, same as a file that was never
 * generated by ComfyUI at all.
 */
function extractByByteScan(bytes: Uint8Array): ComfyMetadata {
  const text = new TextDecoder("utf-8", { fatal: false }).decode(bytes);
  return {
    prompt: extractJsonValueForKey(text, "prompt") as ComfyGraph | undefined,
    workflow: extractJsonValueForKey(text, "workflow"),
  };
}

/**
 * Opportunistically extracts ComfyUI generation metadata from an image or
 * video file, or returns `null` if none is found (either because the file
 * wasn't generated by ComfyUI, or its save node doesn't embed metadata —
 * see comfyToAsset.ts's caller for how this feeds the editor's "import as
 * much as possible" behavior). Never throws.
 */
export async function extractComfyMetadata(file: File): Promise<ComfyMetadata | null> {
  try {
    const bytes = new Uint8Array(await file.arrayBuffer());
    const raw = isPng(bytes) ? extractFromPngChunks(bytes) : {};
    if (raw.prompt === undefined && raw.workflow === undefined) {
      Object.assign(raw, extractByByteScan(bytes));
    }
    return sanitize(raw);
  } catch {
    return null;
  }
}
