/**
 * Shared column model for the asset table's header row and every data row,
 * so columns stay pixel-aligned regardless of tree nesting depth — only the
 * "tree" column (chevron + grip handle) grows with depth via inner padding,
 * every other column has a fixed track. See docs/planning/04-editor.md Part B.
 *
 * A subset of columns is `optional`: hidden by default and toggled on via
 * the table's "Columns" menu, for fields that are edited far less often
 * (timecodes, generated-at timestamp, media path/MIME) than the core ones. Both the
 * header and every `TreeRow` filter `ASSET_TABLE_COLUMNS` the same way
 * (`isColumnVisible`), so the grid template and the actual rendered cells
 * never drift out of sync. See docs/planning/04-editor.md Part J.
 *
 * Labels use the spec's own field names/wording (spec/README.md §2.3,
 * spec/glossary.md) rather than editor-invented terms — e.g. "Generated by"
 * for `generatedBy`, not "Artist" — and match the standalone viewer's
 * column labels (demo/viewer/viewer.js `COLUMNS`) wherever both show the
 * same field, so a term means the same thing everywhere in the project.
 */
export interface AssetTableColumn {
  key: string;
  label: string;
  /** CSS grid track sizing for this column, e.g. "170px" or "minmax(240px,2.5fr)". */
  width: string;
  /** Hidden by default; shown via the "Columns" toggle menu. */
  optional?: boolean;
}

