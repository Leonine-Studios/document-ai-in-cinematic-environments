import { useState } from "react";
import { X } from "lucide-react";
import type { DaiceAsset } from "@leoninestudios/daice-chain-core";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";

/**
 * Shown above the table whenever 2+ rows are selected. Each field applies
 * independently (an explicit "Set" click, not on blur) so a blank field
 * never accidentally clears every selected asset's existing value. See
 * docs/planning/04-editor.md Part F.
 */
export function BulkEditBar({
  count,
  onApply,
  onClear,
  providerSuggestions,
  modelSuggestions,
}: {
  count: number;
  onApply: (patch: Partial<DaiceAsset>) => void;
  onClear: () => void;
  providerSuggestions?: string[];
  modelSuggestions?: string[];
}) {
  const [provider, setProvider] = useState("");
  const [model, setModel] = useState("");
  const [prompt, setPrompt] = useState("");
  const [seed, setSeed] = useState("");
  const [generatedByName, setGeneratedByName] = useState("");
  const [generatedByEmail, setGeneratedByEmail] = useState("");

  return (
    <div className="flex flex-wrap items-center gap-2 rounded-md border border-ai/40 bg-ai/5 px-3 py-2">
      <p className="shrink-0 text-xs font-medium text-muted-foreground">{count} assets selected</p>

      <div className="flex items-center gap-1">
        <Input value={provider} onChange={(e) => setProvider(e.target.value)} placeholder="Provider" className="h-8 w-28" list="bulk-provider-suggestions" />
        {providerSuggestions && providerSuggestions.length > 0 && (
          <datalist id="bulk-provider-suggestions">
            {providerSuggestions.map((s) => (
              <option key={s} value={s} />
            ))}
          </datalist>
        )}
        <Button size="sm" variant="outline" className="h-8" onClick={() => onApply({ provider: provider || undefined })}>
          Set provider
        </Button>
      </div>

      <div className="flex items-center gap-1">
        <Input value={model} onChange={(e) => setModel(e.target.value)} placeholder="Model" className="h-8 w-28" list="bulk-model-suggestions" />
        {modelSuggestions && modelSuggestions.length > 0 && (
          <datalist id="bulk-model-suggestions">
            {modelSuggestions.map((s) => (
              <option key={s} value={s} />
            ))}
          </datalist>
        )}
        <Button size="sm" variant="outline" className="h-8" onClick={() => onApply({ model: model || undefined })}>
          Set model
        </Button>
      </div>

      <div className="flex items-center gap-1">
        <Input value={seed} onChange={(e) => setSeed(e.target.value)} placeholder="Seed" className="h-8 w-20" />
        <Button
          size="sm"
          variant="outline"
          className="h-8"
          onClick={() => {
            const trimmed = seed.trim();
            if (trimmed && !/^-?\d+$/.test(trimmed)) {
              window.alert("Seed must be an integer.");
              return;
            }
            onApply({ seed: trimmed ? Number(trimmed) : undefined });
          }}
        >
          Set seed
        </Button>
      </div>

      <div className="flex items-center gap-1">
        <Input value={prompt} onChange={(e) => setPrompt(e.target.value)} placeholder="Prompt" className="h-8 w-40" />
        <Button size="sm" variant="outline" className="h-8" onClick={() => onApply({ prompt: prompt || undefined })}>
          Set prompt
        </Button>
      </div>

      <div className="flex items-center gap-1">
        <Input value={generatedByName} onChange={(e) => setGeneratedByName(e.target.value)} placeholder="Generated by name" className="h-8 w-32" />
        <Input value={generatedByEmail} onChange={(e) => setGeneratedByEmail(e.target.value)} placeholder="Email" className="h-8 w-32" />
        <Button
          size="sm"
          variant="outline"
          className="h-8"
          onClick={() =>
            onApply({ generatedBy: generatedByName.trim() ? { name: generatedByName.trim(), email: generatedByEmail.trim() || undefined } : undefined })
          }
        >
          Set generated by
        </Button>
      </div>

      <Button size="sm" variant="ghost" className="ml-auto h-8" onClick={onClear}>
        <X className="h-4 w-4" /> Clear selection
      </Button>
    </div>
  );
}
