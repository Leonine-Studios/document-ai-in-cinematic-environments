import { flattenForTable, type DaicePackage } from "@leoninestudios/daice-chain-core";

/**
 * One row of the metadata-only package overview shared by the Excel and PDF
 * exporters. Deliberately contains no media bytes — `mediaPath`/
 * `mediaMimeType` are included as plain text pointers only, never the file
 * itself. See docs/planning/04-editor.md deliverable 7.
 */
export interface OverviewRow {
  id: string;
  kind: "AI-generated" | "Non-AI";
  provider: string;
  model: string;
  seed: string;
  prompt: string;
  generatedBy: string;
  generatedAt: string;
  references: string;
  timecodeIn: string;
  timecodeOut: string;
  mediaPath: string;
  mediaMimeType: string;
}

export const OVERVIEW_COLUMNS: { key: keyof OverviewRow; label: string }[] = [
  { key: "id", label: "Asset" },
  { key: "kind", label: "Kind" },
  { key: "provider", label: "Provider" },
  { key: "model", label: "Model" },
  { key: "seed", label: "Seed" },
  { key: "prompt", label: "Prompt" },
  { key: "generatedBy", label: "Generated by" },
  { key: "generatedAt", label: "Generated at" },
  { key: "references", label: "References" },
  { key: "timecodeIn", label: "TC In" },
  { key: "timecodeOut", label: "TC Out" },
  { key: "mediaPath", label: "Media path" },
  { key: "mediaMimeType", label: "Mime type" },
];

/** Builds one overview row per asset, in the same order as `pkg.assets`, reusing `@leoninestudios/daice-chain-core`'s `flattenForTable` for the derived fields it already computes. */
export function buildOverviewRows(pkg: DaicePackage): OverviewRow[] {
  const flatRows = flattenForTable(pkg);
  return pkg.assets.map((asset, index) => {
    const flat = flatRows[index];
    return {
      id: asset.id,
      kind: flat.aiGenerated ? "AI-generated" : "Non-AI",
      provider: asset.provider ?? "",
      model: asset.model ?? "",
      seed: asset.seed !== undefined ? String(asset.seed) : "",
      prompt: asset.prompt ?? "",
      generatedBy: asset.generatedBy ? [asset.generatedBy.name, asset.generatedBy.email].filter(Boolean).join(" <") + (asset.generatedBy.email ? ">" : "") : "",
      generatedAt: asset.generatedAt ?? "",
      references: asset.references.map((ref) => ref.assetId).join(", "),
      timecodeIn: asset.timecodeIn ?? "",
      timecodeOut: asset.timecodeOut ?? "",
      mediaPath: asset.mediaPath ?? "",
      mediaMimeType: asset.mediaMimeType ?? "",
    };
  });
}
